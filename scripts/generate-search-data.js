/**
 * Generate Localized Search Data
 * Outputs js/search-data.js containing tool metadata and routes for all 7 languages.
 */

const fs = require('fs');
const path = require('path');
const { LANGUAGES, LANGUAGE_CODES } = require('../data/languages');
const { ROUTES, TOOL_KEYS } = require('../data/routes');
const { TOOL_TRANSLATIONS } = require('../data/translations/tools');

const searchData = {};

LANGUAGE_CODES.forEach(lang => {
  searchData[lang] = TOOL_KEYS.map(toolKey => {
    const route = ROUTES[toolKey];
    const trans = TOOL_TRANSLATIONS[toolKey][lang];
    return {
      id: route.origFolder,
      key: toolKey,
      name: trans.name,
      url: route[lang],
      category: trans.category,
      desc: trans.lead,
      keywords: trans.keywords || []
    };
  });
});

const content = `/**
 * ZamTools Localized Search Index
 * Auto-generated by scripts/generate-search-data.js
 */
window.ZAM_LOCALIZED_TOOLS = ${JSON.stringify(searchData, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'js', 'search-data.js'), content, 'utf8');
console.log('Successfully generated js/search-data.js');
